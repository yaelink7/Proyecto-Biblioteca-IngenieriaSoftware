    private void EditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditarActionPerformed
        // TODO add your handling code here:                                      
        int filaSeleccionada = TablaUsuarios.getSelectedRow();
        if (filaSeleccionada >= 0) {
            Usuario usuarioSeleccionado = listaUsuarios.get(filaSeleccionada);
            GUIUsuario ventanaEdicion = new GUIUsuario();
            ventanaEdicion.ModoEdicion(usuarioSeleccionado);
            ventanaEdicion.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Selecciona minimo un usuario de la tabla para poder editar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_EditarActionPerformed

    private void EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarActionPerformed
        // TODO add your handling code here:                                       
        int filaSeleccionada = TablaUsuarios.getSelectedRow();
        if (filaSeleccionada >= 0) {
            String nombreUsuario = (String) TablaUsuarios.getValueAt(filaSeleccionada, 1);
            int confirmar = JOptionPane.showConfirmDialog(this, "¿Estás seguro de Ejecutar al usuario " + nombreUsuario + "?\nEsta acción no se puede deshacer.",
                "Confirmar Eliminación",JOptionPane.YES_NO_OPTION);

            if (confirmar == JOptionPane.YES_OPTION) {
                try {
                    Usuario usuarioAEliminar = listaUsuarios.get(filaSeleccionada);
                    UsureroDao.eliminarUsuario(usuarioAEliminar.getId());
                    listaUsuarios.remove(filaSeleccionada);
                    UsureroDao.guardarUsuarioCSV(listaUsuarios);
                    cargarDatosTablaUsuario();
                    JOptionPane.showMessageDialog(this, "Hemos ejecutado correctamente al Usuario Patron", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                } catch (IOException e) {
                    JOptionPane.showMessageDialog(this, "Error con el CSV" + e.getMessage());
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona un usuario de la tabla para eliminar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_EliminarActionPerformed

