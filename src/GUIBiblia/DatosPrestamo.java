    private void DevolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DevolverActionPerformed
        // TODO add your handling code here:
        int fila = tablaRateros.getSelectedRow();
    
        if (fila >= 0) {
            String estado = (String) tablaRateros.getValueAt(fila, 5);

            if (estado.equals("Devuelto")) {
                JOptionPane.showMessageDialog(this, "Este libro ya fue devuelto.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }
            int idPrestamo = (int) tablaRateros.getValueAt(fila, 0);
            String titulo = (String) tablaRateros.getValueAt(fila, 1);

            int confirm = JOptionPane.showConfirmDialog(this, 
                    "¿Confirmar devolución de: " + titulo + "?", 
                    "Devolución", JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.YES_OPTION) {
                PrestamoDao dao = new PrestamoDao();
                boolean exito = dao.realizarDevolucion(idPrestamo);

                if (exito) {
                    JOptionPane.showMessageDialog(this, "Libro devuelto exitosamente. Inventario actualizado.");
                    cargarDatosPrestamo();
                    
                } else {
                    JOptionPane.showMessageDialog(this, "Error al procesar la devolución.");
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Selecciona un préstamo de la tabla.");
        }
    }//GEN-LAST:event_DevolverActionPerformed

