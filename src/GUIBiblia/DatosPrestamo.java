    private void cargarDatosPrestamo() {
        PrestamoDao predao= new PrestamoDao();
        
        try {
            List<PrestamoDao.DataPrestamoEspecifica> historial = predao.obtenerHistorialPrestamos();
            
            modeloTablapres.setRowCount(0);
            
            for (PrestamoDao.DataPrestamoEspecifica datacos : historial) {
                modeloTablapres.addRow(new Object[]{
                    datacos.idPrestamo,
                    datacos.tituloLibro,
                    datacos.nombreUsuario,
                    datacos.fechaPrestamo,
                    datacos.fechaDevolucion,
                    datacos.estado
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }

