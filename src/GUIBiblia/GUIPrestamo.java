    private void actualizarDias() {
        String mes = (String) PresMes.getSelectedItem();
        String mesd = (String) DevMes.getSelectedItem();
        if (mes == null || mesd == null) return;
        int diasMaximos = 31;
        int diasMaximosD = 31;
        switch (mes) {
            case "Abril":
            case "Junio":
            case "Septiembre":
            case "Noviembre":
                diasMaximos = 30;
                diasMaximosD = 30;
                break;
            case "Febrero":
                    diasMaximos = 28;
                    diasMaximosD = 28;
                break;
            default:
                diasMaximos = 31;
                diasMaximosD = 31;
                break;
        }
        String diaSeleccionado = (String) PresDia.getSelectedItem();
        String diaSeleccionadoD = (String) DevDia.getSelectedItem();
        javax.swing.DefaultComboBoxModel<String> modeloDias = new javax.swing.DefaultComboBoxModel<>();
        javax.swing.DefaultComboBoxModel<String> modeloDiasD = new javax.swing.DefaultComboBoxModel<>();
        for (int i = 1; i <= diasMaximos; i++) {
            modeloDias.addElement(String.valueOf(i));
        }
        for (int i = 1; i <= diasMaximosD; i++) {
            modeloDiasD.addElement(String.valueOf(i));
        }
        PresDia.setModel(modeloDias);
        DevDia.setModel(modeloDiasD);
        if (diaSeleccionado != null||diaSeleccionadoD != null) {
            int diaAnt = Integer.parseInt(diaSeleccionado);
            if (diaAnt <= diasMaximos) {
                PresDia.setSelectedItem(diaSeleccionado);
            }
            int diaAntD = Integer.parseInt(diaSeleccionadoD);
            if (diaAntD <= diasMaximosD) {
                DevDia.setSelectedItem(diaSeleccionadoD);
            }

      }
    }
    
    private void cargarLibrosBox() {
        LibroDao libroDao = new LibroDao("datosLibros.csv");
        TituLibro.removeAllItems();
        try {
            List<Libro> listaLibros = libroDao.obtenerLibros();
            for (Libro libro : listaLibros) {
                if (libro.getExistencias() > 0) { 
                    TituLibro.addItem(libro.getTitulo());
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar libros: " + e.getMessage());
        }
    }
    
        private void cargarUsuariosBox() {
        DAOBiblia.UsuarioDao usuarioDao = new DAOBiblia.UsuarioDao("datosUsuario.csv");
        NomUsuario.removeAllItems();

        try {
            List<ClasesBiblia.Usuario> lista = usuarioDao.obtenerUsuarios();
            for (ClasesBiblia.Usuario u : lista) {
                NomUsuario.addItem(u.getId() + " - " + u.getNombre() + " " + u.getApellido());
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar usuarios: " + e.getMessage());
        }
    }
    
