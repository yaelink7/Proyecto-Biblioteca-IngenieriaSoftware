    private void PrestamoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_PrestamoActionPerformed
        // TODO add your handling code here:
        String tituloSeleccionado = (String) TituLibro.getSelectedItem();
        String usuarioSeleccionado = (String) NomUsuario.getSelectedItem();
        String diaP = (String) PresDia.getSelectedItem();
        String mesP = obtenerNumeroMes((String) PresMes.getSelectedItem());
        String anoP = (String) PresAno.getSelectedItem();
        String fechaPrestamoSQL = anoP + "-" + mesP + "-" + diaP;

        String diaD = (String) DevDia.getSelectedItem();
        String mesD = obtenerNumeroMes((String) DevMes.getSelectedItem());
        String anoD = (String) DevAno.getSelectedItem();
        String fechaDevolucionSQL = anoD + "-" + mesD + "-" + diaD;
        
        if (tituloSeleccionado == null || usuarioSeleccionado == null) {
         JOptionPane.showMessageDialog(this, "Selecciona un libro y un usuario.");
         return;
        }

        try {
            String[] partesUsuario = usuarioSeleccionado.split(" - ");
            int idUsuario = Integer.parseInt(partesUsuario[0]);
            DAOBiblia.LibroDao libroDao = new DAOBiblia.LibroDao("datosLibros.csv");
            ClasesBiblia.Libro libro = libroDao.buscarTitulo(tituloSeleccionado);

            if (libro != null) {
                if (libro.getExistencias() > 0) {
                    DAOBiblia.PrestamoDao prestamoDao = new DAOBiblia.PrestamoDao();
                    boolean exito = prestamoDao.registrarPrestamo(libro.getIdLibro(), idUsuario, fechaPrestamoSQL, fechaDevolucionSQL);
                    if (exito) {
                        JOptionPane.showMessageDialog(this, "Préstamo realizado con éxito.\nQuedan " + (libro.getExistencias() - 1) + " ejemplares.");

                    } else {
                        JOptionPane.showMessageDialog(this, "Error al guardar en base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "No hay existencias disponibles de este libro.", "Agotado", JOptionPane.WARNING_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this, "Error: Libro no encontrado en BD.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_PrestamoActionPerformed

